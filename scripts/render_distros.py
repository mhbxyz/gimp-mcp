#!/usr/bin/env python3
"""Render the distribution table of docs/compatibility.md from ci/distros/distros.json.

python scripts/render_distros.py          # rewrite the section in place
python scripts/render_distros.py --check  # exit 1 when the doc is out of date
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "ci" / "distros" / "distros.json"
DOC = ROOT / "docs" / "compatibility.md"
START, END = "<!-- distributions:start -->", "<!-- distributions:end -->"


def render(data: dict) -> str:
    survey = data["survey"]
    lines = [
        START,
        "<!-- Generated by scripts/render_distros.py from ci/distros/distros.json. Do not edit by hand. -->",
        "",
        f"Survey of {survey['date']} ({survey['source']}). Requirement: {survey['requirement']}.",
        "",
        "| Distribution | GIMP | Status | Packages / reason |",
        "|---|---|---|---|",
    ]
    for item in data["distributions"]:
        status = "**supported** — verified in CI" if item["status"] == "supported" else "unsupported"
        detail = f"`{item['packages']}`" if item["status"] == "supported" else item["reason"]
        lines.append(f"| {item['name']} | {item['gimp']} | {status} | {detail} |")
    lines += [
        "",
        "Supported distributions are checked by `.github/workflows/distros.yml` (on releases, weekly and when",
        "the matrix changes): the wheel is installed in a clean container of each one (base image pinned by",
        "digest) and drives the distribution's own GIMP over MCP (`ci/run-distro.sh <id>` locally).",
        END,
    ]
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    text = DOC.read_text(encoding="utf-8")
    start, end = text.index(START), text.index(END) + len(END)
    updated = text[:start] + render(json.loads(DATA.read_text())) + text[end:]
    if "--check" in argv:
        if updated != text:
            print("docs/compatibility.md is out of date: run scripts/render_distros.py", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(updated, encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
